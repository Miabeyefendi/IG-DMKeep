  async function resourceToBlob(resource) {
    if (resource.blob) return resource.blob;
    if (!resource.url) return null;
    const attempts = [
      { credentials: 'include', mode: 'cors', cache: 'force-cache' },
      { credentials: 'omit', mode: 'cors', cache: 'force-cache' },
      { credentials: 'same-origin', mode: 'cors', cache: 'force-cache' }
    ];

    let lastError = null;
    for (const init of attempts) {
      try {
        const response = await fetch(resource.url, init);
        if (!response.ok) {
          lastError = new Error('Fetch failed: ' + resource.url + ' [' + response.status + ']');
          continue;
        }
        const blob = await response.blob();
        if (blob && blob.size > 0) return blob;
        lastError = new Error('Empty blob: ' + resource.url);
      } catch (error) {
        lastError = error;
      }
    }

    throw lastError || new Error('Fetch failed: ' + resource.url);
  }

  async function resourceToBytes(resource) {
    const blob = await resourceToBlob(resource);
    if (!blob) return null;
    return new Uint8Array(await blob.arrayBuffer());
  }

  async function exportZip() {
    const items = getExportItems();
    if (!items.length) {
      setStatus(t('statusNoData'), 'warn');
      return;
    }

    setStatus(t('statusZip'), 'info');
    const baseName = sanitizeFileName(state.conversationTitle || 'instagram-dm');
    const payload = buildExportPayload(items);
    const imageUrls = state.scanOptions.includeImages ? getImageUrlsFromItems(items) : [];
    const audioResources = state.scanOptions.includeAudio ? getAudioResourcesFromItems(items) : [];
    const reelUrls = state.scanOptions.includeReels ? getReelUrlsFromItems(items) : [];
    const zipEntries = [
      { name: 'conversation.json', data: textToBytes(JSON.stringify(payload, null, 2)) },
      { name: 'conversation.txt', data: textToBytes(buildTextExport(items, { includeLinks: true })) },
      { name: 'conversation.md', data: textToBytes(buildMarkdownExport(items)) },
      {
        name: 'links/reels.txt',
        data: textToBytes(reelUrls.map(url => {
          const meta = state.reelMeta.get(url);
          return meta && meta.videoUrl ? url + '\n' + meta.videoUrl : url;
        }).join('\n\n'))
      }
    ];

    if (state.scanOptions.includeBinaryMedia) {
      const binaryTargets = [];

      imageUrls.forEach(url => {
        binaryTargets.push({
          folder: 'media/images',
          resource: { url, mime: '', key: url, kind: 'image' }
        });
      });

      audioResources.forEach(item => {
        binaryTargets.push({
          folder: 'media/audio',
          resource: item
        });
      });

      reelUrls.forEach(url => {
        const meta = state.reelMeta.get(url);
        if (meta && meta.videoUrl) {
          binaryTargets.push({
            folder: 'media/reels',
            resource: { url: meta.videoUrl, mime: 'video/mp4', key: meta.videoUrl, kind: 'reel' }
          });
        }
      });

      for (let i = 0; i < binaryTargets.length; i++) {
        const target = binaryTargets[i];
        const progress = 35 + Math.round((i / Math.max(binaryTargets.length, 1)) * 60);
        setProgress(progress);
        setStatus(t('statusZipFetch') + ' (' + (i + 1) + '/' + binaryTargets.length + ')', 'info');

        try {
          const bytes = await resourceToBytes(target.resource);
          if (!bytes) continue;
          const mime = target.resource.mime || '';
          const fallbackExt = target.resource.kind === 'audio' ? '.m4a' : (target.resource.kind === 'reel' || target.resource.kind === 'video' ? '.mp4' : '.jpg');
          const ext = getExtFromMime(mime) || getExtFromUrl(target.resource.url, fallbackExt) || '';
          const filename = sanitizeFileName(target.resource.kind + '-' + String(i + 1).padStart(3, '0')) + ext;
          zipEntries.push({ name: target.folder + '/' + filename, data: bytes });
        } catch (error) {
          console.warn('Skipped ZIP binary:', target.resource.url, error);
        }
      }
    }

    const blob = buildStoredZip(zipEntries);
    downloadBlob(blob, baseName + '-' + nowStamp() + '.zip');
    setProgress(100);
    setStatus(t('statusZipReady'), 'success');
  }

  async function scanConversation() {
    if (state.scanning) return;
    const shouldRestoreAfterScan = !state.minimized;

    readThreadMeta();
    installResourceHooks();
    state.resources.clear();
    try {
      for (const entry of performance.getEntriesByType('resource')) {
        if (entry && entry.name) registerResource(entry.name, 'performance-reset', { hint: 'performance-reset' });
      }
    } catch (error) {
    }

    const container = findContainer();
    if (!container) {
      setStatus(t('statusNoContainer'), 'error');
      return;
    }

    state.scanning = true;
    state.timeline = [];
    state.seenTimelineKeys = new Set();
    state.selectedKeys.clear();
    state.reelMeta.clear();
    state.pendingReelAssignments = [];
    state.finishedAt = '';
    setProgress(0);
    setStatus(t('statusPreparing'), 'info');
    els.scanBtn.disabled = true;
    els.scanBtn.textContent = t('scanningBtn');
    setMinimized(true);
    updateStatsUi();
    renderTimeline();

    try {
      console.log('InstaDM-Scraper v2 by @miabeyefendi');
      console.log(GITHUB_URL);

      setStatus(t('statusTop'), 'info');

      let previousHeight = -1;
      let stableCount = 0;
      while (stableCount < 5) {
        container.scrollTop = -container.scrollHeight * 2;
        await sleep(1500);
        if (container.scrollHeight === previousHeight) stableCount++;
        else stableCount = 0;
        previousHeight = container.scrollHeight;
      }

      await sleep(3000);
      setProgress(12);
      setStatus(t('statusScanning'), 'info');

      const collectedItems = [];
      const seenKeys = new Set();
      const handledReelTriggers = new Set();
      const viewHeight = container.clientHeight;
      let stepCount = 0;
      let noChangeCount = 0;

      while (true) {
        const beforeTexts = getVisibleBubbleTexts(container);
        const screenItems = scrapeScreen(container);
        let newCount = 0;

        for (const item of screenItems) {
          const key = buildScanSeenKey(item);
          if (seenKeys.has(key)) continue;
          seenKeys.add(key);
          collectedItems.push(item);
          newCount++;
        }

        if (state.scanOptions.includeReels) {
          const reelCaptured = await openVisibleReelAndCapture(container, handledReelTriggers);
          if (reelCaptured) {
            // Immediately flush pending reel assignments into collectedItems
            // at the current scan position (correct chronological placement)
            state.pendingReelAssignments.forEach(assignment => {
              if (assignment.applied) return;
              const urlsToAdd = (assignment.urls || []).filter(url => url);
              if (!urlsToAdd.length) return;

              urlsToAdd.forEach(url => {
                const scanKey = 'V|' + url;
                if (seenKeys.has(scanKey)) return;
                seenKeys.add(scanKey);
                collectedItems.push({
                  type: 'media',
                  mediaType: 'reel',
                  url: url,
                  key: url,
                  text: '',
                  isSent: assignment.isSent,
                  timestampLabel: assignment.timestampLabel || '',
                  top: assignment.top + 0.01
                });
              });
              assignment.applied = true;
            });
            continue;
          }
        }

        stepCount++;
        setProgress(Math.min(97, 15 + stepCount));
        setStatus(t('statusScanning') + ' ' + stepCount + ' | +' + newCount, 'info');

        const oldScrollTop = container.scrollTop;
        container.scrollTop = oldScrollTop + Math.floor(viewHeight * 0.5);

        let waited = 0;
        while (waited < 5000) {
          await sleep(300);
          waited += 300;

          const afterTexts = getVisibleBubbleTexts(container);
          let hasNew = false;
          for (const text of afterTexts) {
            if (!beforeTexts.has(text)) {
              hasNew = true;
              break;
            }
          }

          if (hasNew) break;
          if (container.scrollTop === oldScrollTop && waited > 1000) break;
        }

        await sleep(500);

        if (container.scrollTop >= -5 || container.scrollTop === oldScrollTop) {
          noChangeCount++;
          if (noChangeCount >= 3) {
            container.scrollTop = 0;
            await sleep(2000);
            const finalItems = scrapeScreen(container);
            for (const item of finalItems) {
              const key = buildScanSeenKey(item);
              if (seenKeys.has(key)) continue;
              seenKeys.add(key);
              collectedItems.push(item);
            }
            break;
          }
        } else {
          noChangeCount = 0;
        }

        if (stepCount > 500) {
          console.warn('InstaDM v2 scan step limit reached');
          break;
        }
      }

      state.timeline = collectedItems;
      state.seenTimelineKeys = seenKeys;
      refreshTimelineFromResources();

      setStatus(t('statusScanning') + ' reels...', 'info');
      await resolveKnownReels();
      renderTimeline();

      state.finishedAt = new Date().toISOString();
      setProgress(100);
      setStatus(t('statusDone'), 'success');
    } catch (error) {
      console.error('InstaDM scan failed:', error);
      setStatus(String(error && error.message ? error.message : error), 'error');
    } finally {
      state.scanning = false;
      if (shouldRestoreAfterScan) setMinimized(false);
      els.scanBtn.disabled = false;
      els.scanBtn.textContent = state.timeline.length ? t('rescanBtn') : t('scanBtn');
    }
  }

