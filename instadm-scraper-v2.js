  function extractInstagramMediaUrls(value) {
    const source = normalizeUrlText(value);
    const out = [];
    const patterns = [
      /https?:\/\/(?:www\.)?instagram\.com\/(?:reel\/[^\s"'<>\\]+|share\/reel\/[^\s"'<>\\]+|share\/r\/[^\s"'<>\\]+|p\/[^\s"'<>\\]+)/gi,
      /\/(?:reel\/[^\s"'<>\\]+|share\/reel\/[^\s"'<>\\]+|share\/r\/[^\s"'<>\\]+|p\/[^\s"'<>\\]+)/gi
    ];

    patterns.forEach(pattern => {
      const matches = source.match(pattern) || [];
      matches.forEach(match => {
        const resolved = normalizeInstagramContentUrl(match);
        if (resolved) out.push(resolved);
      });
    });

    return uniqBy(out, item => item);
  }

