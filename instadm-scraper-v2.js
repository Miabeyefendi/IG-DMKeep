  async function openVisibleReelAndCapture(container, handledTriggers) {
    const triggers = getVisibleReelTriggers(container).filter(item => !handledTriggers.has(item.signature));
    if (!triggers.length) return false;

    const selected = triggers[0];
    handledTriggers.add(selected.signature);
    selected.group.dataset.instadmReelHandled = '1';

    const scrollBefore = container.scrollTop;
    const previousUrl = window.location.href;
    const capturedUrls = new Set();
    const bubble = selected.group.querySelector(bubbleSel) || selected.target.closest(bubbleSel) || selected.group;
    const bubbleText = extractBubbleText(bubble).join(' ');
    const bubbleTop = Math.round(bubble.getBoundingClientRect().top);
    const bubbleTimestamp = extractTimestampNearBubble(bubble);
    const bubbleIsSent = detectIsSent(bubble, container.getBoundingClientRect());

    selected.target.click();

    let waited = 0;
    while (waited < 7000) {
      await sleep(150);
      waited += 150;
      const liveUrl = normalizeInstagramContentUrl(window.location.href);
      if (isPopupContentUrl(liveUrl)) capturedUrls.add(liveUrl);
      if (document.querySelector('[role="dialog"]') || window.location.href !== previousUrl) break;
    }

    let observeWindow = 0;
    while (observeWindow < 4000) {
      await sleep(150);
      observeWindow += 150;
      const liveUrl = normalizeInstagramContentUrl(window.location.href);
      if (isPopupContentUrl(liveUrl)) capturedUrls.add(liveUrl);
    }

    capturedUrls.forEach(url => {
      registerResource(url, 'dialog-route', { kind: 'reel', hint: isPostUrl(url) ? 'dialog-post-url' : 'dialog-reel' });
    });

    if (capturedUrls.size) {
      state.pendingReelAssignments.push({
        signature: selected.signature,
        isSent: bubbleIsSent,
        timestampLabel: bubbleTimestamp,
        text: safeText(bubbleText),
        top: bubbleTop,
        urls: Array.from(capturedUrls),
        applied: false
      });
    }

    await captureDialogMedia(true);
    await sleep(600);
    await closeActivePopup();
    await sleep(900);
    container.scrollTop = scrollBefore;
    await sleep(400);
    return true;
  }

