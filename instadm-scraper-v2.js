  function buildTextExport(items, options) {
    const exportItems = items || state.timeline;
    const includeLinks = !options || options.includeLinks !== false;
    const lines = [];
    let lastDate = '';

    for (const item of exportItems) {
      if (item.type === 'date') {
        lastDate = item.text;
        lines.push('---');
        lines.push(t('exportDateLabel') + ': ' + item.text);
        continue;
      }

      if (item.type === 'media') {
        const label = item.mediaType === 'reel'
          ? t('reelLabel')
          : item.mediaType === 'audio'
              ? t('audioLabel')
              : t('imageLabel');
        lines.push(t('standaloneMedia') + ': [' + label + '] ' + (item.url || ''));
        continue;
      }

      if (item.type !== 'message') continue;

      if (item.dateText && item.dateText !== lastDate) {
        lastDate = item.dateText;
        lines.push('---');
        lines.push(t('exportDateLabel') + ': ' + item.dateText);
      }

      const senderLabel = getDirectionLabel(item.isSent);
      let line = senderLabel + ': ' + (item.text || t('attachmentOnly'));
      if (item.timestampLabel) line += ' [' + item.timestampLabel + ']';
      if (item.liked) line += ' [' + t('likeBadge') + ': ' + item.liked + ']';
      lines.push(line);

      if (includeLinks && state.scanOptions.includeImages) {
        (item.images || []).forEach((image, index) => {
          lines.push('  [' + t('exportImageLabel') + ' ' + (index + 1) + '] ' + image.url);
        });
      }

      if (includeLinks && state.scanOptions.includeAudio) {
        (item.audio || []).forEach((audio, index) => {
          if (audio.url) lines.push('  [' + t('exportAudioLabel') + ' ' + (index + 1) + '] ' + audio.url);
        });
      }

      if (includeLinks && state.scanOptions.includeReels) {
        (item.links || []).forEach(link => {
          if (link.kind === 'reel') {
            lines.push('  [Reel] ' + link.url);
            const meta = state.reelMeta.get(link.url);
            if (meta && meta.videoUrl) lines.push('  [' + t('exportReelVideoLabel') + '] ' + meta.videoUrl);
          }
        });
      }
    }

    lines.push('');
    lines.push(t('generatedByLabel') + ' - ' + GITHUB_URL);
    return lines.join('\n');
  }

  function buildMarkdownExport(items) {
    const exportItems = items || state.timeline;
    const lines = ['# ' + (state.conversationTitle || t('threadFallback')), '', '- ' + t('exportedAtLabel') + ': ' + new Date().toISOString(), '- ' + t('exportThreadLabel') + ': ' + state.threadUrl, ''];
    let lastDate = '';

    for (const item of exportItems) {
      if (item.type === 'date') {
        lastDate = item.text;
        lines.push('## ' + item.text, '');
        continue;
      }

      if (item.type === 'media') {
        const label = item.mediaType === 'reel'
          ? t('reelLabel')
          : item.mediaType === 'audio'
              ? t('audioLabel')
              : t('imageLabel');
        lines.push('- **' + t('standaloneMedia') + '** [' + label + '](' + (item.url || '#') + ')');
        continue;
      }

      if (item.type !== 'message') continue;

      if (item.dateText && item.dateText !== lastDate) {
        lastDate = item.dateText;
        lines.push('## ' + item.dateText, '');
      }

      const direction = getDirectionLabel(item.isSent);
      lines.push('- **' + direction + '** ' + (item.text || t('attachmentOnly')));
      if (item.timestampLabel) lines.push('  - ' + t('exportTimeLabel') + ': ' + item.timestampLabel);
      if (item.liked) lines.push('  - ' + t('likeBadge') + ': ' + item.liked);
      (item.images || []).forEach(image => lines.push('  - ' + t('exportImageLabel') + ': ' + image.url));
      (item.audio || []).forEach(audio => { if (audio.url) lines.push('  - ' + t('exportAudioLabel') + ': ' + audio.url); });
      (item.links || []).forEach(link => {
        if (link.kind === 'reel') {
          lines.push('  - ' + t('reelLabel') + ': ' + link.url);
          const meta = state.reelMeta.get(link.url);
          if (meta && meta.videoUrl) lines.push('  - ' + t('exportReelVideoLabel') + ': ' + meta.videoUrl);
        } else {
          lines.push('  - ' + t('exportLinkLabel') + ': ' + link.url);
        }
      });
      lines.push('');
    }

    return lines.join('\n');
  }

