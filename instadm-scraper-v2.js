  function isDateText(text) {
    const value = safeText(text);
    if (!value) return false;
    const normalized = normalizeDateLookupText(value);
    if (/\d{1,2}\s+(oca|sub|mar|nis|may|haz|tem|agu|eyl|eki|kas|ara)\s+\d{4}\s+\d{2}:\d{2}/i.test(normalized)) return true;
    if (/\d{1,2}\s+(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)\s+\d{4}/i.test(normalized)) return true;
    if (/\d{2}\.\d{2}\.\d{4},?\s*\d{2}:\d{2}/.test(normalized)) return true;
    if (/^(pzt|sal|car|per|cum|cts|paz)\s+\d{2}:\d{2}$/i.test(normalized)) return true;
    if (/^(mon|tue|wed|thu|fri|sat|sun)\s+\d{2}:\d{2}$/i.test(normalized)) return true;
    if (/^(today|yesterday|bugun|dun)\b.*\b\d{1,2}:\d{2}\b/i.test(normalized)) return true;
    if (/^\d{1,2}:\d{2}$/.test(normalized)) return true;
    return false;
  }

  function isDateMarkerNode(node, containerRect) {
    if (!node || !node.getBoundingClientRect) return false;
    if (node.closest('#' + APP_ID)) return false;
    if (node.closest(bubbleSel)) return false;
    if (node.closest('header, button, a')) return false;

    const rect = node.getBoundingClientRect();
    if (!rect.height || rect.top > window.innerHeight || rect.bottom < 0) return false;
    if (rect.width > containerRect.width * 0.9) return false;

    return true;
  }

  function formatTimestampValue(value) {
    const raw = safeText(value);
    if (!raw) return '';

    const parsed = new Date(raw);
    if (Number.isNaN(parsed.getTime())) return raw;

    return String(parsed.getHours()).padStart(2, '0') + ':' + String(parsed.getMinutes()).padStart(2, '0');
  }

  function formatDateMarkerValue(value) {
    const raw = safeText(value);
    if (!raw) return '';

    const parsed = new Date(raw);
    if (Number.isNaN(parsed.getTime())) return raw;

    const locale = state.lang === 'tr' ? 'tr-TR' : (state.lang === 'es' ? 'es-ES' : 'en-US');
    const datePart = parsed.toLocaleDateString(locale, {
      day: 'numeric',
      month: 'short',
      year: 'numeric'
    });
    return datePart + ' ' + String(parsed.getHours()).padStart(2, '0') + ':' + String(parsed.getMinutes()).padStart(2, '0');
  }

  function getDateMarkerLabel(node) {
    if (!node) return '';

    const candidates = [
      safeText(node.textContent),
      safeText(node.getAttribute && node.getAttribute('aria-label')),
      safeText(node.getAttribute && node.getAttribute('title'))
    ];

    for (const candidate of candidates) {
      if (candidate && isDateText(candidate)) return candidate;
    }

    if (node.getAttribute) {
      const formatted = formatDateMarkerValue(node.getAttribute('datetime') || '');
      if (formatted && isDateText(formatted)) return formatted;
    }

    return '';
  }

  function getTimeElementLabel(timeEl) {
    if (!timeEl) return '';

    const candidates = [
      safeText(timeEl.textContent),
      safeText(timeEl.getAttribute && timeEl.getAttribute('aria-label')),
      safeText(timeEl.getAttribute && timeEl.getAttribute('title'))
    ];

    for (const candidate of candidates) {
      if (!candidate) continue;
      const match = candidate.match(/\b\d{1,2}:\d{2}\b/);
      if (match) return match[0];
      if (/^\d{1,2}:\d{2}$/.test(candidate)) return candidate;
    }

    return formatTimestampValue(timeEl.getAttribute('datetime') || '');
  }

  function detectIsSent(bubble, containerRect) {
    const rect = bubble.getBoundingClientRect();
    const bg = window.getComputedStyle(bubble).backgroundColor;
    const rgb = bg.match(/\d+/g);
    if (rgb && rgb.length >= 3) {
      const r = +rgb[0];
      const g = +rgb[1];
      const b = +rgb[2];
      if (b > 160 && r < 170 && g < 170) return true;
      if (r > 45 && g > 45 && b > 45 && rect.left > containerRect.left + containerRect.width * 0.45) return true;
    }
    return rect.left + rect.width / 2 > containerRect.left + containerRect.width * 0.58;
  }

  function extractTimestampNearBubble(bubble) {
    if (!bubble || !bubble.getBoundingClientRect) return '';

    const bubbleRect = bubble.getBoundingClientRect();
    const bubbleCenter = bubbleRect.top + bubbleRect.height / 2;
    const scopes = [];
    const seenScopes = new Set();
    const seenTimes = new Set();
    const group = bubble.closest('[role="group"]');
    if (group) scopes.push(group);

    let node = bubble;
    for (let depth = 0; depth < 4 && node; depth++) {
      scopes.push(node);
      node = node.parentElement;
    }

    let bestLabel = '';
    let bestDistance = Number.POSITIVE_INFINITY;

    scopes.forEach(scope => {
      if (!scope || !scope.querySelectorAll || seenScopes.has(scope)) return;
      seenScopes.add(scope);

      scope.querySelectorAll('time').forEach(timeEl => {
        if (!timeEl || seenTimes.has(timeEl)) return;
        if (timeEl.closest('#' + APP_ID)) return;

        const rect = timeEl.getBoundingClientRect();
        if (!rect.height || rect.top > window.innerHeight || rect.bottom < 0) return;

        const label = getTimeElementLabel(timeEl);
        if (!label) return;

        seenTimes.add(timeEl);

        const timeCenter = rect.top + rect.height / 2;
        const distance = Math.abs(timeCenter - bubbleCenter);
        if (distance < bestDistance) {
          bestDistance = distance;
          bestLabel = label;
        }
      });
    });

    if (bestLabel) return bestLabel;

    let fallbackNode = bubble;
    for (let depth = 0; depth < 6 && fallbackNode; depth++) {
      const timeEl = fallbackNode.querySelector && fallbackNode.querySelector('time');
      const label = getTimeElementLabel(timeEl);
      if (label) return label;
      fallbackNode = fallbackNode.parentElement;
    }

    return '';
  }

  function extractLikeEmoji(bubble) {
    let likeEmoji = '';
    let searchEl = bubble.parentElement;

    for (let i = 0; i < 8; i++) {
      if (!searchEl) break;
      searchEl.querySelectorAll('span').forEach(span => {
        const value = safeText(span.textContent);
        if (['❤', '❤️', '♥', '😂', '😍', '🔥', '😢', '😮', '👍', '👏', '🥰', '💯', '😊', '😆', '🙏'].includes(value)) {
          const rect = span.getBoundingClientRect();
          if (rect.width > 0 && rect.width < 35) likeEmoji = value;
        }
      });
      searchEl.querySelectorAll('[aria-label]').forEach(node => {
        const label = String(node.getAttribute('aria-label') || '').toLowerCase();
        if (label.includes('unlike') || label.includes('begeniyi kaldir')) {
          if (!likeEmoji) likeEmoji = '❤';
        }
      });
      if (likeEmoji) break;
      searchEl = searchEl.parentElement;
    }

    return likeEmoji;
  }

