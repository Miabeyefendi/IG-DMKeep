  async function captureDialogMedia(force) {
    if (state.scanning && !force) return 0;
    const dialogs = Array.from(document.querySelectorAll('[role="dialog"]')).filter(node => !node.closest('#' + APP_ID));
    const foundUrls = new Set();

    const canonicalCandidates = [
      document.querySelector('link[rel="canonical"]')?.getAttribute('href') || '',
      document.querySelector('meta[property="og:url"]')?.getAttribute('content') || '',
      document.querySelector('meta[name="twitter:url"]')?.getAttribute('content') || '',
      window.location.href
    ];

    canonicalCandidates.forEach(value => {
      const url = normalizeInstagramContentUrl(value);
      if (isPopupContentUrl(url)) foundUrls.add(url);
    });

    if (!foundUrls.size && isPopupContentUrl(window.location.href)) {
      foundUrls.add(normalizeInstagramContentUrl(window.location.href));
    }

    dialogs.forEach(dialog => {
      extractInstagramMediaUrls(dialog.innerHTML || '').forEach(url => foundUrls.add(url));

      dialog.querySelectorAll('a[href], [href], [src], [data-url], [data-href]').forEach(node => {
        if (!node.attributes) return;
        Array.from(node.attributes).forEach(attribute => {
          extractInstagramMediaUrls(attribute.value || '').forEach(url => foundUrls.add(url));
        });
      });

      dialog.querySelectorAll('video, source').forEach(node => {
        const src = absoluteUrl(node.currentSrc || node.src || node.getAttribute('src') || '');
        if (!src) return;
        registerResource(src, 'dialog-video', { kind: 'video', mime: 'video/mp4', hint: 'dialog-video' });
      });
    });

    let added = 0;
    foundUrls.forEach(url => {
      if (!isPopupContentUrl(url)) return;
      const beforeSize = state.resources.size;
      registerResource(url, 'dialog-reel', { kind: 'reel', hint: isPostUrl(url) ? 'dialog-post-url' : 'dialog-reel' });
      if (state.resources.size > beforeSize) added++;
    });

    if (added && state.timeline.length) {
      refreshTimelineFromResources();
      await resolveKnownReels();
      renderTimeline();
    }

    return added;
  }

  function getVisibleReelTriggers(container) {
    const out = [];
    const seen = new Set();

    container.querySelectorAll('[aria-label]').forEach(node => {
      const label = safeText(node.getAttribute('aria-label') || '').toLowerCase();
      if (!/klip|clip|reel/i.test(label)) return;

      const target = node.closest('button, a, [role="button"], [role="group"]') || node;
      const group = target.closest('[role="group"]') || target;
      if (group.dataset.instadmReelHandled === '1') return;
      const rect = target.getBoundingClientRect();
      if (!rect.height || rect.top > window.innerHeight || rect.bottom < 0) return;

      const signature = [
        Math.round(rect.top),
        Math.round(rect.left),
        safeText(group.textContent || '').slice(0, 80),
        label
      ].join('|');

      if (seen.has(signature)) return;
      seen.add(signature);
      out.push({ target, group, signature });
    });

    return out;
  }

