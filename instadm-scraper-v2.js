  function extractBubbleLinks(bubble) {
    const out = [];
    const scope = bubble.closest('[role="group"]') || bubble;

    function pushLink(url, text, sourceHint) {
      if (!url) return;
      let kind = 'link';
      if (isReelUrl(url)) kind = 'reel';
      else if (isPostUrl(url)) kind = 'post';
      else return;

      if (/\/direct\//i.test(url)) return;
      if (/https?:\/\/(?:www\.)?instagram\.com\/[^/?#]+\/?$/i.test(url)) return;

      out.push({
        kind,
        url,
        text: safeText(text)
      });
      registerResource(url, sourceHint || 'dom-link', { hint: kind });
    }

    scope.querySelectorAll('a[href]').forEach(anchor => {
      const href = resolveInstagramRedirectUrl(anchor.getAttribute('href') || '');
      pushLink(href, anchor.textContent, 'dom-link');
    });

    scope.querySelectorAll('*').forEach(node => {
      if (!node.attributes) return;
      Array.from(node.attributes).forEach(attribute => {
        const rawValue = String(attribute.value || '');
        if (!rawValue) return;
        extractInstagramMediaUrls(rawValue).forEach(url => {
          pushLink(url, node.textContent || attribute.name, 'dom-attr-link');
        });
      });
    });

    extractInstagramMediaUrls(scope.innerHTML || '').forEach(url => {
      pushLink(url, 'html', 'dom-html-link');
    });

    return uniqBy(out, item => item.kind + '|' + item.url);
  }

  function extractBubbleAudio(bubble) {
    const out = [];
    const scope = bubble.closest('[role="group"]') || bubble;

    scope.querySelectorAll('audio, video, source').forEach(node => {
      const src = absoluteUrl(node.currentSrc || node.src || node.getAttribute('src') || '');
      const type = String(node.getAttribute('type') || '').toLowerCase();
      if (!src) return;

      const isAudio = node.tagName.toLowerCase() === 'audio' || type.startsWith('audio/') || /audio|voice|\.(m4a|aac|mp3|wav|ogg|oga)(\?|$)/i.test(src);
      if (!isAudio) return;

      out.push({
        kind: 'audio',
        url: src,
        type
      });
      registerResource(src, 'dom-audio', { mime: type, hint: 'audio' });
    });

    scope.querySelectorAll('*').forEach(node => {
      if (!node.attributes) return;
      Array.from(node.attributes).forEach(attribute => {
        const rawValue = String(attribute.value || '');
        if (!rawValue) return;
        if (!/blob:|audio|voice|m4a|aac|mp3|wav|ogg|playback|listen/i.test(rawValue)) return;

        const src = absoluteUrl(rawValue);
        const attrName = String(attribute.name || '').toLowerCase();
        const isAudioUrl = src && (/^blob:/i.test(src) || /\.(m4a|aac|mp3|wav|ogg|oga)(\?|$)/i.test(src) || /audio|voice|playback|listen/i.test(src));
        if (!isAudioUrl && !/audio|voice|playback|listen/.test(attrName)) return;

        out.push({
          kind: 'audio',
          url: src,
          type: attrName
        });
        if (src) registerResource(src, 'dom-audio-attr', { hint: attrName || 'audio-attr' });
      });
    });

    extractRawUrls(scope.innerHTML || '').forEach(url => {
      if (!/\.(m4a|aac|mp3|wav|ogg|oga)(\?|$)/i.test(url) && !/audio|voice|playback|listen/i.test(url)) return;
      out.push({
        kind: 'audio',
        url,
        type: 'html-audio'
      });
      registerResource(url, 'dom-audio-html', { hint: 'audio-html' });
    });

    scope.querySelectorAll('button, [role="button"], [aria-label]').forEach(node => {
      const label = String(node.getAttribute('aria-label') || node.textContent || '').toLowerCase();
      if (!label) return;
      if (!/voice|audio|ses|oynat|play/i.test(label)) return;
      out.push({
        kind: 'audio-control',
        label: safeText(label),
        url: ''
      });
    });

    const bubbleText = safeText(scope.textContent || '');
    const hasTranscriptHint = isTranscriptTriggerText(bubbleText);
    const hasDurationHint = /\b\d{1,2}:\d{2}\b/.test(bubbleText);
    if ((hasTranscriptHint || hasDurationHint) && !out.length) {
      out.push({
        kind: 'audio-control',
        label: hasDurationHint ? bubbleText.match(/\b\d{1,2}:\d{2}\b/)[0] : 'audio-control',
        url: ''
      });
    }

    return uniqBy(out, item => (item.url || '') + '|' + (item.label || ''));
  }

  function buildTimelineKey(item) {
    if (item.type === 'date') return 'date|' + item.text;
    if (item.type === 'media') return 'media|' + item.mediaType + '|' + (item.url || item.key || item.text || '');

    const links = (item.links || []).map(link => link.url).join('|').slice(0, 240);
    const images = (item.images || []).map(image => image.url).join('|').slice(0, 240);
    const audio = (item.audio || []).map(track => track.url || track.label || '').join('|').slice(0, 240);
    return [
      'msg',
      item.isSent ? '1' : '0',
      item.timestampLabel || '',
      item.text || '',
      links,
      images,
      audio,
      item.liked || ''
    ].join('|');
  }

  function buildScanSeenKey(item) {
    if (item.type === 'date') return 'D|' + item.text;
    if (item.type === 'media') return 'V|' + (item.key || item.url || item.text || '');
    return [
      'M',
      item.isSent ? '1' : '0',
      item.timestampLabel || '',
      String(item.text || item.previewText || '').slice(0, 120),
      (item.images || []).length,
      (item.audio || []).length,
      (item.links || []).filter(link => link.kind === 'reel' || link.kind === 'post').length,
      item.liked || ''
    ].join('|');
  }

  function scrapeScreen(container) {
    const items = [];
    const containerRect = container.getBoundingClientRect();

    container.querySelectorAll('span, div, time').forEach(node => {
      if (!isDateMarkerNode(node, containerRect)) return;
      const text = getDateMarkerLabel(node);
      if (!text || text.length <= 3 || text.length >= 60) return;

      const child = node.querySelector('span, div, time');
      if (child && getDateMarkerLabel(child)) return;
      items.push({ type: 'date', text, top: node.getBoundingClientRect().top });
    });

    // V1-style CSS color fallback: detect gray-colored date spans
    if (items.filter(i => i.type === 'date').length === 0) {
      container.querySelectorAll('span').forEach(s => {
        if (s.closest('#' + APP_ID)) return;
        const rect = s.getBoundingClientRect();
        if (!rect.height || rect.top > window.innerHeight || rect.bottom < 0) return;
        const color = window.getComputedStyle(s).color;
        const rgb = color.match(/\d+/g);
        if (!rgb) return;
        const r = +rgb[0], g = +rgb[1], b = +rgb[2];
        if (r > 90 && r < 210 && g > 90 && g < 210 && b > 90 && b < 210 && Math.abs(r - g) < 20 && Math.abs(g - b) < 20) {
          const text = safeText(s.textContent);
          if (text.length > 3 && text.length < 60 && isDateText(text)) {
            items.push({ type: 'date', text, top: rect.top });
          }
        }
      });
    }

    // Second fallback: check all spans/divs without color restriction
    if (items.filter(i => i.type === 'date').length === 0) {
      container.querySelectorAll('span, div').forEach(s => {
        if (s.closest('#' + APP_ID)) return;
        if (s.closest(bubbleSel)) return;
        const rect = s.getBoundingClientRect();
        if (!rect.height || rect.top > window.innerHeight || rect.bottom < 0) return;
        const text = safeText(s.textContent);
        if (text.length > 5 && text.length < 60 && isDateText(text)) {
          const child = s.querySelector('span, div');
          if (child && isDateText(safeText(child.textContent))) return;
          items.push({ type: 'date', text, top: rect.top });
        }
      });
    }

    container.querySelectorAll('a[href]').forEach(anchor => {
      const rect = anchor.getBoundingClientRect();
      if (!rect.height || rect.top > window.innerHeight || rect.bottom < 0) return;
      if (anchor.closest(bubbleSel)) return;

      const href = absoluteUrl(anchor.getAttribute('href') || '');
      if (!href) return;

      if (href.includes('/reel/')) {
        items.push({
          type: 'media',
          mediaType: 'reel',
          url: href,
          key: href,
          top: rect.top
        });
        registerResource(href, 'standalone-link', { hint: 'reel' });
      }
    });

    container.querySelectorAll('img').forEach(img => {
      const rect = img.getBoundingClientRect();
      if (!rect.height || rect.top > window.innerHeight || rect.bottom < 0) return;
      if (img.closest(bubbleSel)) return;

      const src = absoluteUrl(img.currentSrc || img.src || '');
      if (!src) return;
      if (/profile|avatar/i.test(src)) return;
      if ((img.width || img.naturalWidth || 0) < 60) return;

      items.push({
        type: 'media',
        mediaType: 'image',
        url: src,
        key: src,
        top: rect.top
      });
      registerResource(src, 'standalone-image', { hint: 'image' });
    });

    container.querySelectorAll(bubbleSel).forEach(bubble => {
      const rect = bubble.getBoundingClientRect();
      if (!rect.height || rect.top > window.innerHeight || rect.bottom < 0) return;

      const texts = extractBubbleText(bubble);
      const images = extractBubbleImages(bubble);
      const links = extractBubbleLinks(bubble);
      const audio = extractBubbleAudio(bubble);
      const isSent = detectIsSent(bubble, containerRect);
      const timestampLabel = extractTimestampNearBubble(bubble);

      applyPendingReelAssignments(items, bubble, isSent, timestampLabel);

      if (!texts.length && !images.length && !links.length && !audio.length) return;

      items.push({
        type: 'message',
        text: texts.join(' ') || '',
        previewText: texts.join(' ') || t('attachmentOnly'),
        isSent,
        liked: extractLikeEmoji(bubble),
        timestampLabel,
        sender: '',
        images,
        links,
        audio,
        top: rect.top
      });
    });

    items.sort((a, b) => a.top - b.top);
    return items;
  }

  function readThreadMeta() {
    let username = '';

    // Try to extract @username from profile links in the header
    document.querySelectorAll('header a[href], [role="banner"] a[href]').forEach(node => {
      if (username) return;
      if (node.closest('#' + APP_ID)) return;
      const href = node.getAttribute('href') || '';
      // Instagram profile links: /username/ (exclude system paths)
      const match = href.match(/^\/([a-zA-Z0-9._]+)\/?$/);
      if (!match) return;
      const candidate = match[1].toLowerCase();
      if (/^(direct|explore|reels|stories|accounts|p|reel|share|about|legal|privacy|terms|emails|session|challenge)$/i.test(candidate)) return;
      username = '@' + candidate;
    });

    // Fallback: try to find profile link near the conversation container
    if (!username) {
      const container = findContainer();
      if (container) {
        let headerArea = container.previousElementSibling;
        if (!headerArea) headerArea = container.parentElement;
        if (headerArea) {
          headerArea.querySelectorAll('a[href]').forEach(node => {
            if (username) return;
            if (node.closest('#' + APP_ID)) return;
            if (node.closest(bubbleSel)) return;
            const href = node.getAttribute('href') || '';
            const match = href.match(/^\/([a-zA-Z0-9._]+)\/?$/);
            if (!match) return;
            const candidate = match[1].toLowerCase();
            if (/^(direct|explore|reels|stories|accounts|p|reel|share|about|legal|privacy|terms|emails|session|challenge)$/i.test(candidate)) return;
            username = '@' + candidate;
          });
        }
      }
    }

    if (username) {
      state.conversationTitle = username;
    } else {
      // Final fallback: use display name from header text
      const titleCandidates = [];
      const excludePattern = /^(instagram|search|notifications|active now|aktif|online|audio call|voice call|video call|arama|direct|direkt|mesaj|message|home|explore|reels|shop|g[o\u00f6]r[u\u00fc]nt[u\u00fc]l[u\u00fc])$/i;
      document.querySelectorAll('header h1, header h2, header span, header a').forEach(node => {
        if (node.closest('#' + APP_ID)) return;
        const text = safeText(node.textContent);
        if (!text || text.length > 80 || text.length < 2) return;
        if (excludePattern.test(text)) return;
        if (/^\d+$/.test(text)) return;
        titleCandidates.push(text);
      });
      state.conversationTitle = titleCandidates[0] || state.conversationTitle || t('threadFallback');
    }

    const avatar = Array.from(document.querySelectorAll('header img, [role="banner"] img')).find(node => !node.closest('#' + APP_ID));
    state.headerAvatar = avatar ? absoluteUrl(avatar.currentSrc || avatar.src || '') : state.headerAvatar;
  }

