  function hydrateCapturedResourcesIntoMessages() {
    const usedAudio = new Set(getAllAudioResources().map(item => item.url).filter(Boolean));
    const audioPool = Array.from(state.resources.values()).filter(resource => resource.kind === 'audio' && resource.url && !usedAudio.has(resource.url));

    state.timeline.forEach(item => {
      if (item.type !== 'message' || !item.audio || !item.audio.length || !audioPool.length) return;
      const needsAudioUrl = item.audio.some(entry => !entry.url);
      if (!needsAudioUrl) return;

      const nextAudio = audioPool.shift();
      if (!nextAudio) return;

      let assigned = false;
      item.audio = item.audio.map(entry => {
        if (entry.url || assigned) return entry;
        assigned = true;
        return {
          kind: entry.kind || 'audio',
          label: entry.label || '',
          url: nextAudio.url,
          type: entry.type || nextAudio.mime || ''
        };
      });
    });

  }

  function applyPendingReelAssignments(items, bubble, isSent, timestampLabel) {
    if (!state.pendingReelAssignments.length) return;

    const bubbleTop = Math.round(bubble.getBoundingClientRect().top);
    let insertOffset = 0.01;

    state.pendingReelAssignments.forEach(assignment => {
      if (assignment.applied) return;
      if (assignment.isSent !== isSent) return;
      if (assignment.timestampLabel && timestampLabel && assignment.timestampLabel !== timestampLabel) return;

      const topMatch = Math.abs(assignment.top - bubbleTop) <= 80;
      if (!topMatch) return;

      const urlsToAdd = assignment.urls.filter(url => url);
      if (!urlsToAdd.length) return;

      urlsToAdd.forEach(url => {
        items.push({
          type: 'media',
          mediaType: 'reel',
          url,
          key: url,
          text: '',
          isSent: assignment.isSent,
          timestampLabel: assignment.timestampLabel || '',
          top: bubbleTop + insertOffset
        });
        insertOffset += 0.01;
      });

      assignment.urls.forEach(url => {
        registerResource(url, 'pending-reel-assignment', {
          kind: 'reel',
          hint: isPostUrl(url) ? 'assigned-post-reel' : 'assigned-reel'
        });
      });
      assignment.urls = assignment.urls.filter(url => !urlsToAdd.includes(url));
      if (!assignment.urls.length) assignment.applied = true;
    });
  }

