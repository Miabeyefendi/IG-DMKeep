          const contentType = String(this.getResponseHeader('content-type') || '').toLowerCase();
          registerResource(responseUrl, 'xhr', { mime: contentType, hint: 'xhr' });
          if (contentType.includes('application/json') && typeof this.responseText === 'string' && this.responseText.length < 10000000) {
            extractUrlsFromText(this.responseText, 'xhr-text');
            try {
              inspectJsonTree(JSON.parse(this.responseText), 'xhr-json');
            } catch (error) {
            }
          }
