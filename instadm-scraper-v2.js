  function decodeHtmlEntities(value) {
    const area = document.createElement('textarea');
    area.innerHTML = String(value || '');
    return area.value;
  }

  function unescapeJsonishUrl(value) {
    return decodeHtmlEntities(String(value || ''))
      .split('\\u0026').join('&')
      .split('\\/').join('/')
      .split('\\').join('');
  }

  function extractBetween(text, marker) {
    const source = String(text || '');
    const startIndex = source.indexOf(marker);
    if (startIndex === -1) return '';
    const valueStart = startIndex + marker.length;
    const valueEnd = source.indexOf('"', valueStart);
    if (valueEnd === -1) return '';
    return source.slice(valueStart, valueEnd);
  }

  function findFirstUrlContaining(text, needle) {
    const source = String(text || '');
    const hitIndex = source.indexOf(needle);
    if (hitIndex === -1) return '';
    const startIndex = source.lastIndexOf('http', hitIndex);
    if (startIndex === -1) return '';

    let endIndex = startIndex;
    while (endIndex < source.length) {
      const char = source[endIndex];
      if (char === '"' || char === '\'' || char === '<' || char === ' ' || char === '\n' || char === '\r' || char === '\t') break;
      endIndex++;
    }

    return source.slice(startIndex, endIndex);
  }

  async function resolveReelMetadata(url) {
    if (!url) return null;
    if (state.reelMeta.has(url)) return state.reelMeta.get(url);

    let meta = { reelUrl: url, videoUrl: '', thumbnailUrl: '' };
    try {
      const response = await fetch(url, { credentials: 'include' });
      const html = await response.text();
      const ogVideo = extractBetween(html, 'property="og:video" content="') || extractBetween(html, '"video_url":"');
      const ogImage = extractBetween(html, 'property="og:image" content="') || extractBetween(html, '"thumbnail_url":"');
      const fallbackVideo = findFirstUrlContaining(html, '.mp4');

      if (ogVideo) meta.videoUrl = unescapeJsonishUrl(ogVideo);
      else if (fallbackVideo) meta.videoUrl = unescapeJsonishUrl(fallbackVideo);

      if (ogImage) meta.thumbnailUrl = unescapeJsonishUrl(ogImage);

      if (meta.videoUrl) registerResource(meta.videoUrl, 'reel-resolve', { kind: 'video', hint: 'reel-video' });
      if (meta.thumbnailUrl) registerResource(meta.thumbnailUrl, 'reel-resolve', { kind: 'image', hint: 'reel-thumb' });
    } catch (error) {
      meta = { reelUrl: url, videoUrl: '', thumbnailUrl: '', error: String(error && error.message || error) };
    }

    state.reelMeta.set(url, meta);
    return meta;
  }

